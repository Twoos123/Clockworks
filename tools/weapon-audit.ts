// Audits every weapon in config/item.dat: groups weapons by the base config their combat
// comes from, and records each family's attacks (animations, speeds, timing windows,
// lunges, hit shapes, fire actions) and charge attack. Writes docs/research/weapon-data.md.
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join } from "node:path";
import { importBinary } from "../src/export/BinaryImport.ts";
import { applyArguments, getArg } from "../src/config/params.ts";
import { nodeInflate, skDir } from "./common.ts";

const load = async (p: string) => {
  const r: any = (await importBinary(new Uint8Array(readFileSync(join(skDir(), "rsrc", p))), nodeInflate)).root;
  const list: any[] = Array.isArray(r) ? r : r.array ?? [];
  return new Map<string, any>(list.map(c => [c.name, c]));
};
const items = await load("config/item.dat");
const attacks = await load("config/attack.dat");
const fireActions = await load("config/fire_action.dat");
const kind = (o: any) => (o?.$class ?? "").split(".").pop();

/** Follows Derived chains, returning the implementation and the base config's name. */
function resolve(lib: Map<string, any>, ref: any, field: string) {
  let base = "";
  for (let i = 0; i < 12 && ref?.name; i++) {
    const b = lib.get(ref.name);
    if (!b) return { impl: null, base };
    const cfg = applyArguments(b, ref);
    const impl = cfg.implementation;
    if (impl?.$class?.endsWith("$Derived") && impl[field]) { ref = impl[field]; continue; }
    base = ref.name;
    return { impl, base };
  }
  return { impl: null, base };
}

function anim(path?: string) {
  if (!path) return "-";
  return existsSync(join(skDir(), "rsrc", path)) ? path.replace("character/pc/", "") : `${path} (missing)`;
}

function describeAttack(ref: any) {
  const { impl: a, base } = resolve(attacks, ref, "attack");
  if (!a) return { name: ref?.name, missing: true };
  const fires = (a.fireRefs ?? []).filter((f: any) => f?.ref).map((f: any) => {
    const fa = resolve(fireActions, f.ref, "action");
    const shape = getArg(f.ref, "Shape") as any;
    return { action: f.ref.name, base: fa.base, delay: getArg(f.ref, "Delay"), shape: kind(shape?.shape ?? shape),
      bullet: (getArg(f.ref, "Bullet") as any)?.name ?? (getArg(f.ref, "Actor") as any)?.name };
  });
  const imp = a.impulseReceived;
  return {
    name: ref.name, base, kind: kind(a),
    start: anim(a.start?.name), fire: anim(a.fire?.name), end: anim(a.end?.name),
    speeds: [a.startSpeed ?? 1, a.fireSpeed ?? 1, a.endSpeed ?? 1].map((x: number) => +x.toFixed(2)).join("/"),
    clear: a.clear, rearm: a.rearm, land: a.land, interruptable: !!a.interruptable,
    impulse: imp ? `${imp.translation?.x ?? 0} fwd, ${imp.translation?.y ?? 0} side, ${imp.duration ?? "?"}ms after ${imp.delay ?? 0}ms` : "(default)",
    fires,
  };
}

const families = new Map<string, { weapons: string[]; type: string; impl: any }>();
for (const [name] of items) {
  if (!name.startsWith("Weapon/") || name.includes("/Parts/")) continue;
  const { impl, base } = resolve(items, { name }, "item");
  if (!impl?.attacks && !impl?.chargedAttack) continue;
  // family key: the base config plus its attack names (weapons share bases but differ in args)
  const key = base + " :: " + (impl.attacks ?? []).map((a: any) => a?.ref?.name).join(" | ");
  const f = families.get(key) ?? { weapons: [] as string[], type: kind(impl) as string, impl };
  f.weapons.push(name);
  families.set(key, f);
}

const lines: string[] = [];
lines.push("# Weapon data audit", "", `Generated by tools/weapon-audit.ts from the install's config libraries. ${families.size} weapon families (distinct base config and attack list) covering ${[...families.values()].reduce((s, f) => s + f.weapons.length, 0)} weapons.`, "");
lines.push("Speeds are the start/fire/end animation speed multipliers. Clear, rearm and land are milliseconds. Impulse is the movement the attack gives the knight; \"(default)\" means the config omits it and the game-code default applies.", "");
const byType = new Map<string, [string, any][]>();
for (const e of families) { const t = e[1].type; byType.set(t, [...(byType.get(t) ?? []), e]); }
for (const [type, list] of [...byType].sort()) {
  lines.push(`## ${type} (${list.length} families)`, "");
  for (const [key, f] of list.sort((a, b) => b[1].weapons.length - a[1].weapons.length)) {
    const impl = f.impl;
    lines.push(`### ${key.split(" :: ")[0]}`, "");
    lines.push(`Weapons (${f.weapons.length}): ${f.weapons.slice(0, 8).map((w: string) => w.split("/").pop()).join(", ")}${f.weapons.length > 8 ? ", ..." : ""}`, "");
    const extras: string[] = [];
    for (const k of ["maxChain", "chargeTime", "clipSize", "reloadTime", "fuseTime", "displaySpeed", "rarity"]) if (impl[k] !== undefined) extras.push(`${k} ${impl[k]}`);
    if (extras.length) lines.push(`Properties: ${extras.join(", ")}`, "");
    lines.push("| # | Attack | Start / fire / end animation | Speeds | Clear | Rearm | Impulse | Fire actions |", "|---|---|---|---|---|---|---|---|");
    (impl.attacks ?? []).forEach((r: any, i: number) => {
      const a: any = r?.ref ? describeAttack(r.ref) : { name: "?" };
      lines.push(`| ${i + 1} | ${(a.name ?? "").split("/").slice(-2).join("/")} | ${a.start} / ${a.fire} / ${a.end} | ${a.speeds} | ${a.clear ?? "-"} | ${a.rearm ?? "-"} | ${a.impulse} | ${(a.fires ?? []).map((x: any) => `${x.action}${x.bullet ? " → " + x.bullet : ""}${x.shape ? " [" + x.shape + "]" : ""}`).join("; ")} |`);
    });
    if (impl.chargedAttack) {
      const c: any = describeAttack(impl.chargedAttack);
      lines.push(`| charge | ${(c.name ?? "").split("/").pop()} | ${c.start} / ${c.fire} / ${c.end} | ${c.speeds} | ${c.clear ?? "-"} | ${c.rearm ?? "-"} | ${c.impulse} | ${(c.fires ?? []).map((x: any) => x.action + (x.bullet ? " → " + x.bullet : "")).join("; ")} |`);
    }
    lines.push("");
  }
}
writeFileSync("docs/research/weapon-data.md", lines.join("\n"));
console.log(`wrote docs/research/weapon-data.md: ${families.size} families`);
for (const [t, l] of byType) console.log(t, l.length, "families,", l.reduce((s, f) => s + f[1].weapons.length, 0), "weapons");
